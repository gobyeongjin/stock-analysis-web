import os
import psycopg
from psycopg.rows import dict_row


def get_postgres_connection():
    database_url = os.getenv("DATABASE_URL")

    if not database_url:
        raise RuntimeError("DATABASE_URL 환경변수가 설정되지 않았습니다.")

    return psycopg.connect(
        database_url,
        row_factory=dict_row,
        connect_timeout=10,
    )


if __name__ == "__main__":
    if not os.getenv("DATABASE_URL"):
        print("DATABASE_URL 미설정: PostgreSQL 연결 테스트 생략")
    else:
        with get_postgres_connection() as conn:
            with conn.cursor() as cursor:
                cursor.execute("SELECT 1 AS connected")
                print("PostgreSQL 연결 성공:", cursor.fetchone())


def init_postgres_db():
    with get_postgres_connection() as conn:
        conn.execute("""
            CREATE TABLE IF NOT EXISTS users (
                id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                email TEXT NOT NULL UNIQUE,
                password_hash TEXT NOT NULL,
                created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
                nickname TEXT,
                ranking_opt_in INTEGER NOT NULL DEFAULT 0
                    CHECK (ranking_opt_in IN (0, 1))
            )
        """)

        # Support existing PostgreSQL users tables that predate profile fields.
        conn.execute("ALTER TABLE users ADD COLUMN IF NOT EXISTS nickname TEXT")
        conn.execute("""
            ALTER TABLE users ADD COLUMN IF NOT EXISTS ranking_opt_in INTEGER
            NOT NULL DEFAULT 0 CHECK (ranking_opt_in IN (0, 1))
        """)

        conn.execute("""
            CREATE TABLE IF NOT EXISTS trades (
                id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                user_id BIGINT NOT NULL REFERENCES users(id)
                    ON DELETE CASCADE,
                ticker TEXT NOT NULL,
                stock_name TEXT NOT NULL,
                trade_type TEXT NOT NULL
                    CHECK (trade_type IN ('BUY', 'SELL')),
                trade_date TEXT NOT NULL,
                price DOUBLE PRECISION NOT NULL CHECK (price > 0),
                quantity INTEGER NOT NULL CHECK (quantity > 0),
                fee DOUBLE PRECISION NOT NULL DEFAULT 0 CHECK (fee >= 0),
                tax DOUBLE PRECISION NOT NULL DEFAULT 0 CHECK (tax >= 0),
                memo TEXT DEFAULT '',
                created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP
            )
        """)

        conn.execute("""
            CREATE INDEX IF NOT EXISTS idx_user_trades
            ON trades(user_id, ticker, trade_date, id)
        """)

        conn.execute("""
            CREATE UNIQUE INDEX IF NOT EXISTS
            idx_users_nickname_unique
            ON users(nickname)
            WHERE nickname IS NOT NULL
        """)


from contextlib import contextmanager


@contextmanager
def postgres_connection():
    with get_postgres_connection() as conn:
        yield conn


def use_postgres():
    return bool(os.getenv("DATABASE_URL"))
